export function matchDrogonChannels(broadcasts) {
  if (!Array.isArray(broadcasts)) return [];
  const result = [];
  for (const source of broadcasts) {
    if (typeof source !== "string" || source.length > 60) continue;
    const canonical = BROADCAST_TO_LINEUP.get(source);
    if (canonical && listed.has(canonical) && !result.includes(canonical)) result.push(canonical);
  }
  return result.slice(0, 6);
}
